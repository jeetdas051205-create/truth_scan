"""
TruthScan AI - AI-Generated Content & Stylometric Authenticity Engine
=====================================================================
Analyzes text for linguistic patterns distinguishing human journalism from LLMs:
- Sentence length variance & burstiness ratio
- LLM formulaic transition phrases and structural signposting
- Attributive journalistic density (named sources, direct quotes, dates)
- Lexical entropy & repetition metrics
"""

import re
import numpy as np

AI_MARKERS = [
    'in conclusion', 'it is important to note', 'delves into', 'testament to',
    'serves as a reminder', 'furthermore', 'moreover', 'tapestry of', 'beacon of',
    'pivotal role', 'vital role', 'it remains to be seen', 'underscore the importance',
    'sheds light on', 'a multifaceted approach', 'navigating the complexities',
    'plays a crucial role', 'in the ever-evolving landscape', 'as we move forward',
    'fostering a culture', 'paramount importance', 'at the forefront of',
    'stand as a testament', 'seamlessly integrated', 'reverberates through',
    'it is worth noting', 'dive deep into', 'holds significant promise'
]

JOURNALISM_ATTRIBUTIONS = [
    'said', 'told', 'reported', 'announced', 'according to', 'spokesperson',
    'confirmed', 'stated', 'testified', 'cited', 'quoted', 'in a statement',
    'press release', 'reuters', 'associated press', 'on tuesday', 'on wednesday',
    'on thursday', 'on friday', 'on monday', 'officials said', 'court filings',
    'interviews with', 'documents show', 'spoke on condition of anonymity'
]


def analyze_ai_content(text: str) -> dict:
    """
    Evaluates whether an article or excerpt is human-written or generated by an AI LLM.
    Returns probability percentages, verdict, and specific detected linguistic markers.
    """
    if not text or len(text.strip().split()) < 8:
        return {
            "ai_probability": 15.0,
            "human_probability": 85.0,
            "verdict": "Authentic Human Journalism",
            "confidence_label": "High Confidence",
            "burstiness": 0.45,
            "ai_markers_found": [],
            "attributions_found": [],
            "summary": "Text contains standard natural human variance."
        }

    words = text.lower().split()
    total_words = len(words)
    text_lower = text.lower()

    # 1. Sentence burstiness analysis
    sentences = [s.strip() for s in re.split(r'[.!?]+', text) if len(s.strip().split()) >= 2]
    if len(sentences) >= 2:
        s_lens = [len(s.split()) for s in sentences]
        mean_len = float(np.mean(s_lens))
        std_len = float(np.std(s_lens))
        burstiness = float(std_len / (mean_len + 1e-5))
    else:
        burstiness = 0.40

    # 2. AI formulaic phrase detection
    found_ai_markers = [phrase for phrase in AI_MARKERS if phrase in text_lower]
    ai_phrase_count = len(found_ai_markers)

    # 3. Journalistic attribution check
    found_attributions = [attr for attr in JOURNALISM_ATTRIBUTIONS if attr in text_lower]
    attr_count = len(found_attributions)

    # 4. Base scoring heuristics
    # Start at neutral 40%
    score = 0.40

    # Burstiness heuristic: AI has uniform sentences (burstiness < 0.35)
    if burstiness < 0.28:
        score += 0.25
    elif burstiness < 0.38:
        score += 0.12
    elif burstiness > 0.55:
        score -= 0.20

    # AI marker phrases impact
    if ai_phrase_count >= 1:
        score += min(0.38, ai_phrase_count * 0.14)

    # Human journalistic sourcing reduces AI probability
    if attr_count >= 2:
        score -= min(0.35, attr_count * 0.10)
    elif attr_count == 1:
        score -= 0.10

    # Normalization (bounded between 3% and 97%)
    score = max(0.03, min(0.97, score))
    ai_pct = round(score * 100, 1)
    human_pct = round((1.0 - score) * 100, 1)

    if ai_pct >= 65.0:
        verdict = "High Probability AI-Generated (LLM)"
        summary = f"Detected {ai_phrase_count} characteristic LLM rhetorical transitions with highly uniform sentence cadence."
    elif ai_pct >= 40.0:
        verdict = "Hybrid / AI-Assisted Content"
        summary = "Text exhibits mixed stylistic elements: structured machine formulation paired with human narrative flow."
    else:
        verdict = "Authentic Human Journalism"
        summary = f"Natural sentence length variance (burstiness: {round(burstiness, 2)}) with verified attribution markers."

    return {
        "ai_probability": ai_pct,
        "human_probability": human_pct,
        "verdict": verdict,
        "burstiness": round(burstiness, 3),
        "ai_markers_found": found_ai_markers[:6],
        "attributions_found": found_attributions[:6],
        "summary": summary
    }

